#!/usr/bin/env python3
"""Vendor the lemma pipeline into hermes-plugin/lemma_pipeline/.

The Hermes catalog installs plugins with `subdir: hermes-plugin`, so the
plugin cannot reach `agent/` at repo root — the pipeline modules the audit,
judge, improve and evidence stages need are copied here under a package
name (`lemma_pipeline`) that cannot collide with hermes-agent's own
`agent` package on sys.path.

`agent/` stays canonical. This script is the only supported way to update
the vendored copy:

    python scripts/sync_hermes_plugin.py          # rewrite hermes-plugin/lemma_pipeline/
    python scripts/sync_hermes_plugin.py --check  # exit 1 if the copy drifted

A pre-commit hook runs --check whenever agent/ or the vendored tree changes.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SRC = REPO_ROOT / "agent"
DST = REPO_ROOT / "hermes-plugin" / "lemma_pipeline"

# Modules reachable from `lemma audit|judge|improve|search` via agent.cli.
# design/evals/audit_room/room_*/mcp_adapter/extract_http are repo-only
# surfaces the plugin never invokes (cli.py imports them lazily).
MODULES = [
    "__init__",
    "cli",
    "auditor",
    "evidence",
    "extract",
    "firecrawl",
    "judge",
    "llm",
    "meta",
    "paperclip",
    "papers",
    "records",
    "script_sandbox",
    "traces",
    "weave_ops",
]

# Comment header, not a docstring: several modules open with
# `from __future__ import annotations`, which must stay the first statement.
HEADER = (
    "# VENDORED COPY — do not edit.\n"
    "#\n"
    "# Generated by scripts/sync_hermes_plugin.py from agent/{name}.py.\n"
    "# The catalog installs hermes-plugin/ standalone (subdir install), so the\n"
    "# plugin carries its own pipeline under the `lemma_pipeline` package name\n"
    "# to avoid colliding with hermes-agent's `agent` package. Edit agent/ and\n"
    "# re-run the sync script.\n"
)

# `from agent import x` / `from agent.y import z` / `import agent[.y]` and
# `-m agent.cli` mentions in docstrings/help text.
REWRITES = [
    (re.compile(r"\bfrom agent\b"), "from lemma_pipeline"),
    (re.compile(r"\bimport agent\b"), "import lemma_pipeline"),
    (re.compile(r"\bagent\.cli\b"), "lemma_pipeline.cli"),
]


def render(name: str) -> str:
    text = (SRC / f"{name}.py").read_text(encoding="utf-8")
    for pattern, repl in REWRITES:
        text = pattern.sub(repl, text)
    if name == "__init__":
        return HEADER.format(name=name) + text
    return HEADER.format(name=name) + text


def generate() -> dict[str, str]:
    return {f"{name}.py": render(name) for name in MODULES}


def sync() -> None:
    files = generate()
    DST.mkdir(parents=True, exist_ok=True)
    for stale in DST.glob("*.py"):
        if stale.name not in files:
            stale.unlink()
    for fname, content in files.items():
        (DST / fname).write_text(content, encoding="utf-8")
    print(f"[sync] wrote {len(files)} modules -> {DST.relative_to(REPO_ROOT)}")


def check() -> int:
    files = generate()
    drifted = []
    for fname, content in files.items():
        path = DST / fname
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            drifted.append(str(path.relative_to(REPO_ROOT)))
    extra = sorted(
        str(p.relative_to(REPO_ROOT)) for p in DST.glob("*.py") if p.name not in files
    )
    drifted.extend(extra)
    if drifted:
        print(
            "[sync] hermes-plugin/lemma_pipeline/ is stale:\n  "
            + "\n  ".join(drifted)
            + "\nRun: python scripts/sync_hermes_plugin.py"
        )
        return 1
    print(f"[sync] {len(files)} vendored modules in sync")
    return 0


def main() -> int:
    if "--check" in sys.argv[1:]:
        return check()
    sync()
    return check()


if __name__ == "__main__":
    raise SystemExit(main())
