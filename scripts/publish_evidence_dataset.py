"""Publish a paper workdir's evidence trail as a Hugging Face Dataset.

Usage:
  .venv/bin/python scripts/publish_evidence_dataset.py papers/<id> [--private]

Uploads the full per-claim evidence (audit scripts, run summaries, figures,
feedback.md, reviewer_reference.py), claims.json, trace.jsonl, and the judge
report — the same layout as the repo workdir, so provenance is exact.
Excludes the source PDF (cite the paper instead) and .trackio logbook state
(published separately as the Space). Generates the dataset card README from
the actual audit report.

Requires HF_TOKEN in .env (or the environment).
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from dotenv import load_dotenv  # noqa: E402

load_dotenv(REPO_ROOT / ".env", override=True)

import os  # noqa: E402

from huggingface_hub import HfApi  # noqa: E402

PAPER_META = {
    "arxiv-2510.10981": {
        "slug": "repro-evidence-icl-provably-bayesian",
        "title": "In-Context Learning Is Provably Bayesian Inference",
        "source": "https://arxiv.org/abs/2510.10981",
        "space": "https://huggingface.co/spaces/Papajams/repro-icl-provably-bayesian",
    },
    "jmlr-22-1228-ca-grokking": {
        "slug": "repro-evidence-grokking-ca-local-rules",
        "title": (
            "Grokking phase transitions in learning local rules with gradient descent"
        ),
        "source": "https://www.jmlr.org/papers/v22/22-1228.html",
        "space": "https://huggingface.co/spaces/Papajams/repro-grokking-ca-local-rules",
    },
}

EXCLUDE_DIRS = {".trackio", "__pycache__"}
EXCLUDE_SUFFIXES = {".pdf", ".log"}
EXCLUDE_FILES = set()


def repo_commit() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except subprocess.CalledProcessError:
        return "unknown"


def build_readme(workdir: Path, meta: dict, private: bool) -> str:
    claims = json.loads((workdir / "claims.json").read_text(encoding="utf-8"))
    report = json.loads(
        (workdir / "results" / "audit_report.json").read_text(encoding="utf-8")
    )
    outcomes = {c["id"]: c for c in report.get("claims", [])}
    supported = sum(1 for c in outcomes.values() if c.get("status") == "supported")
    falsified = sum(1 for c in outcomes.values() if c.get("status") == "falsified")
    other = len(outcomes) - supported - falsified

    rows = []
    for c in claims:
        o = outcomes.get(c["id"], {})
        rows.append(f"| {c['id']} | {c['title']} | {o.get('status', 'not audited')} |")
    table = "\n".join(rows)
    judge = ""
    jp = workdir / "judge_report.json"
    if jp.is_file():
        jr = json.loads(jp.read_text(encoding="utf-8"))
        judge = f"Judge verdict: **{jr.get('verdict')}** ({jr.get('score')})."

    return f"""---
license: mit
tags:
- claim-audit
- reproducibility
- evidence-trail
- agentic-science
- trackio
size_categories:
- n<1K
---

# Evidence trail — {meta["title"]}

Full evidence for an automated claim-by-claim audit of
[{meta["title"]}]({meta["source"]}), produced by
[Lemma](https://github.com/udirobert/lemma), an AI-scientist pipeline built
for re:AGENT (Founders Inc, Aug 15-16 2026).

**Verdict: {supported} supported / {falsified} falsified / {other} inconclusive
of {len(claims)} extracted claims.** {judge}

| Claim | Title | Verdict |
|---|---|---|
{table}

The rendered, human-readable version of this trail is the Trackio logbook:
{meta["space"]}

## What is in this dataset

The exact workdir layout of the audit repository (commit `{repo_commit()}`):

- `claims.json` — extracted claims with per-claim success criteria
- `results/audit_report.json` — final per-claim outcomes
- `results/c<k>/` — for each claim: every audit script the agent wrote
  (`audit_attempt*.py`), each run's `run_attempt*.json` (metrics, wall time,
  exit code), the final `audit_summary.json`, figures (`*.png`),
  `feedback.md` (human reviewer corrections, where used) and
  `reviewer_reference.py` (hand-verified closed-form references, where the
  agent escalated)
- `trace.jsonl` — the append-only trace of every LLM call and tool run
- `judge_report.json` — the automated evidence-trustworthiness judge

Failures are preserved, not curated away: a buggy attempt and its metrics
are part of the evidence.

## Source paper

The audited PDF is not redistributed here; see the link above.

Generated by `scripts/publish_evidence_dataset.py`.
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("workdir", help="paper workdir, e.g. papers/arxiv-2510.10981")
    ap.add_argument("--private", action="store_true")
    args = ap.parse_args()

    workdir = (REPO_ROOT / args.workdir).resolve()
    if not workdir.is_dir():
        print(f"error: {workdir} is not a directory", file=sys.stderr)
        return 1
    meta = PAPER_META.get(workdir.name)
    if meta is None:
        print(f"error: no publish metadata for {workdir.name}", file=sys.stderr)
        return 1

    token = os.environ.get("HF_TOKEN")
    if not token:
        print("error: HF_TOKEN not set (.env)", file=sys.stderr)
        return 1
    username = os.environ.get("HF_USERNAME", "Papajams")
    repo_id = f"{username}/{meta['slug']}"

    readme = build_readme(workdir, meta, args.private)
    staging = workdir / ".dataset_staging"
    if staging.exists():
        import shutil

        shutil.rmtree(staging)
    staging.mkdir()
    try:
        (staging / "README.md").write_text(readme, encoding="utf-8")
        n_files = 0
        for src in sorted(workdir.rglob("*")):
            if not src.is_file():
                continue
            rel = src.relative_to(workdir)
            if any(part in EXCLUDE_DIRS for part in rel.parts):
                continue
            if rel.parts and rel.parts[0] == ".dataset_staging":
                continue
            if src.suffix in EXCLUDE_SUFFIXES or src.name in EXCLUDE_FILES:
                continue
            dst = staging / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(src.read_bytes())
            n_files += 1
        print(f"[publish] staged {n_files} files into {staging.name}/")

        api = HfApi(token=token)
        api.create_repo(
            repo_id,
            repo_type="dataset",
            private=args.private,
            exist_ok=True,
        )
        api.upload_folder(
            repo_id=repo_id,
            repo_type="dataset",
            folder_path=str(staging),
            commit_message=f"Evidence trail: {meta['title']}",
        )
        print(f"[publish] dataset: https://huggingface.co/datasets/{repo_id}")
    finally:
        import shutil

        shutil.rmtree(staging, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
